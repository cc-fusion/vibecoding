import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const base = process.env.TEST_URL || 'http://127.0.0.1:5173';
await fs.mkdir('.source/screenshots',{recursive:true});
const browser = await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>{errors.push(e.message);console.log('PAGE ERROR',e.message);});
page.on('console',m=>{if(m.type()==='error'){errors.push(m.text());console.log('CONSOLE ERROR',m.text());}});
await page.goto(base,{waitUntil:'networkidle'});
await page.waitForSelector('.engine-status:has-text("Engine ready")',{timeout:45000});
await page.waitForFunction(()=>document.querySelector('.viewport-particles')?.textContent !== '0 particles',{timeout:45000});
await page.waitForTimeout(1200);
await page.screenshot({path:'.source/screenshots/playground-desktop.png',fullPage:true});
console.log('PLAYGROUND',await page.locator('.viewport-particles').textContent());
assert.equal(await page.locator('h1').first().textContent(),'Simulation playground');
assert.ok(await page.locator('.simulation-viewport canvas').isVisible());
if(await page.locator('.play-button').textContent()==='Pause')await page.locator('.play-button').click();
await page.waitForTimeout(200);
const initialTime=await page.locator('.timeline>span').first().textContent();
await page.waitForTimeout(200);assert.equal(await page.locator('.timeline>span').first().textContent(),initialTime);
console.log('PASS: Playback pauses.');
await page.getByRole('button',{name:'New scene',exact:true}).click();
await page.waitForSelector('.code-editor textarea');
const original=JSON.parse(await page.locator('.code-editor textarea').inputValue());
assert.equal(original.dim,2);assert.ok(original.objects.length>=3);
await page.getByRole('button',{name:'Add an object',exact:true}).first().click();
await page.getByRole('button',{name:'Add to scene',exact:true}).click();
const updated=JSON.parse(await page.locator('.code-editor textarea').inputValue());
assert.equal(updated.objects.length,original.objects.length+1);
await page.getByRole('button',{name:'Apply & run',exact:true}).click();
await page.waitForSelector('.engine-status:has-text("Engine ready")',{timeout:45000});
await page.waitForTimeout(2000);

assert.equal(await page.locator('.scene-selector select').inputValue(),'custom');
assert.notEqual(await page.locator('.viewport-particles').textContent(),'0 particles');
await page.screenshot({path:'.source/screenshots/custom-scene.png',fullPage:false});
console.log('PASS: JSON editor adds and runs a custom scene.');
await page.locator('.nav-item').filter({hasText:'Scene library'}).click();
await page.getByRole('textbox',{name:'Search scenes'}).fill('splash');
assert.equal(await page.locator('.library-card').count(),1);
await page.getByRole('button',{name:'Save Buoyancy',exact:true}).click();
assert.ok(await page.getByRole('button',{name:'Unsave Buoyancy',exact:true}).isVisible());
await page.locator('.library-open').click();await page.waitForTimeout(700);
assert.equal(await page.locator('.scene-selector select').inputValue(),'buoyancy');
console.log('PASS: Catalog filtering, favorites, and scene loading.');
await page.locator('.nav-item').filter({hasText:'Documentation'}).click();
assert.ok(await page.getByRole('heading',{name:'Good physics starts here.'}).isVisible());
assert.ok(await page.locator('.code-block').first().isVisible());
console.log('PASS: Documentation and copyable code.');
await page.goto(base+'/#playground');
await page.waitForSelector('.engine-status:has-text("Engine ready")',{timeout:45000});
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(500);
await page.screenshot({path:'.source/screenshots/playground-mobile.png',fullPage:true});
assert.ok(await page.locator('.mobile-menu').isVisible());
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
await page.getByRole('button',{name:'Open navigation'}).click();
assert.ok(await page.locator('.sidebar.mobile-open').isVisible());
console.log('PASS: Mobile layout and navigation.');
const lib = await browser.newPage({viewport:{width:1200,height:850}});
lib.on('pageerror',e=>errors.push('Library: '+e.message));
await lib.goto(base+'/examples/quickstart.html',{waitUntil:'networkidle'});
await lib.waitForFunction(()=>window.sim?.ready,{timeout:45000});
await lib.waitForFunction(()=>window.sim.getStats()?.particles>0,{timeout:45000});
await lib.waitForTimeout(500);
const libraryResult=await lib.evaluate(async()=>{
 const sim=window.sim;sim.pause();
 const before=sim.getStats().particles;
 await sim.addParticles({material:'jelly',shape:'sphere',center:[.4,.75],radius:.08,density:3});
 const added=sim.getStats().particles;
 sim.update({gravity:-4, wheelSpeed:180, automaticWheel:true,speed:1});
 const initial=sim.getStats().t;sim.play();
 await new Promise(r=>setTimeout(r,350));sim.pause();
 return {before,added,time:sim.getStats().t-initial,ready:sim.ready,info:sim.info};
});
assert.ok(libraryResult.added>libraryResult.before);assert.ok(libraryResult.time>0);
console.log('PASS: Standalone script API, particle creation, live physics:',JSON.stringify({before:libraryResult.before,added:libraryResult.added,dt:libraryResult.time}));
await lib.screenshot({path:'.source/screenshots/standalone-library.png',fullPage:false});
console.log('BROWSER ERRORS',JSON.stringify(errors));
await browser.close();
if(errors.length)process.exitCode=1;
