#!/bin/bash
# Builds the taichi_mpm full-solver port to WebAssembly (wasm32-wasi reactor)
# and embeds the binaries into src/lib/wasm/mpmWasm.js as base64.
set -e
cd "$(dirname "$0")"
WASI_SDK=${WASI_SDK:-/tmp/wasi-sdk-25.0-x86_64-linux}
CXX="$WASI_SDK/bin/clang++"
FLAGS="-std=c++17 -O3 -fno-exceptions -fno-rtti -mexec-model=reactor -fno-math-errno -ffp-contract=fast \
  -Wl,--strip-all -Wl,-z,stack-size=2097152 -Wl,--initial-memory=67108864 -Wl,--max-memory=2147483648"
mkdir -p build
"$CXX" $FLAGS -msimd128 -mbulk-memory -mnontrapping-fptoint -msign-ext api.cpp -o build/mpm_simd.wasm
"$CXX" $FLAGS api.cpp -o build/mpm_base.wasm
ls -la build/*.wasm
node -e '
const fs = require("fs");
const simd = fs.readFileSync("build/mpm_simd.wasm").toString("base64");
const base = fs.readFileSync("build/mpm_base.wasm").toString("base64");
fs.mkdirSync("../src/sim/wasm", { recursive: true });
fs.writeFileSync("../src/lib/wasm/mpmWasm.js",
  "// AUTO-GENERATED by native/build.sh - WebAssembly build of the taichi_mpm full solver\n" +
  "export const MPM_WASM_SIMD_BASE64 = \"" + simd + "\";\n" +
  "export const MPM_WASM_BASE64 = \"" + base + "\";\n");
console.log("wrote src/lib/wasm/mpmWasm.js", simd.length + base.length, "chars");
'
