import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base=process.env.TEST_URL||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1200,height:800}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/examples/quickstart.html');
await page.waitForFunction(()=>window.sim?.ready,{timeout:30000});
await page.waitForFunction(()=>window.sim.info,{timeout:30000});
const result=await page.evaluate(async()=>{
 const sim=window.sim;
 const definition={id:'live-wheel-test',name:'Live wheel',dim:2,resolution:128,gravity:[0,-9.81],duration:0,boundaries:{floor:true,walls:true,friction:.4},objects:[{id:'water',type:'particles',material:'water',shape:'sphere',center:[.3,.7],radius:.07,density:2,color:'#57b8f5'}]};
 await sim.loadScene(definition,{autoPlay:false});
 await sim.addRigid({id:'live-wheel',type:'rigid',shape:'wheel',center:[.6,.3],radius:.15,blades:8,motion:{enabled:true,speed:90},color:'#e9b870'});
 let angle;const unlisten=sim.on('frame',f=>{if(f.rigids[0]>0){const r=f.rigids;angle=Math.atan2(r[6]-.3,r[5]-.6);}});
 sim.update({wheelSpeed:120,automaticWheel:true,gravity:0});
 sim.play();await new Promise(r=>setTimeout(r,500));sim.pause();
 await new Promise(r=>setTimeout(r,200));
 const before=sim.getStats().particles;
 sim.emitParticles([.4,.8],[0,.5],'jelly','#e68ccf');await new Promise(r=>setTimeout(r,150));
 const after=sim.getStats().particles;
 const t=sim.getStats().t;
 unlisten();sim.dispose();
 return {rigids:sim.getStats().rigids,before,after,t,angle,disposed:sim.disposed};
});
assert.ok(result.rigids>0);assert.ok(result.after>result.before);assert.ok(result.t>0);assert.ok(result.disposed);assert.ok(Number.isFinite(result.angle));
console.log('PASS: Live wheel creation, speed changes, zero gravity, particle emission and disposal.',result);
const downloads=await Promise.all(['/taichi-mpm.js','/docs/taichi-mpm.md','/downloads/taichi-mpm-javascript.zip'].map(async path=>{const response=await page.request.get(base+path);return {path,status:response.status(),bytes:(await response.body()).length};}));
for(const asset of downloads)assert.equal(asset.status,200);
console.log('PASS: All downloadable assets are served.',downloads);
assert.equal(errors.length,0,errors.join('\n'));
await browser.close();
