import fs from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';

await fs.mkdir('public', { recursive: true });
const worker = await build({
  entryPoints: ['src/lib/worker.js'], bundle: true, write: false, format: 'iife', platform: 'browser', target: ['es2020'], minify: true,
  define: { 'process.env.NODE_ENV': '"production"' },
});
const source = worker.outputFiles[0].text;
await fs.writeFile('src/lib/worker-source.js', `// Generated by scripts/build-library.mjs; contains the self-contained worker and WASM.\nexport default ${JSON.stringify(source)};\n`);
const lib = await build({
  entryPoints: ['src/lib/global.js'], bundle: true, write: false, format: 'iife', globalName: 'TaichiMPM', platform: 'browser', target: ['es2020'], minify: true, legalComments: 'inline',
  banner: { js: '/*! TaichiMPM 1.0.0 | JavaScript + WebAssembly | https://github.com/yuanming-hu/taichi_mpm */' },
});
await fs.writeFile('public/taichi-mpm.js', lib.outputFiles[0].text);
console.log(`Standalone library: public/taichi-mpm.js (${Math.round(lib.outputFiles[0].text.length / 1024)} KB)`);
console.log('Self-contained worker generated: src/lib/worker-source.js');
