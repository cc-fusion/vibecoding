// Automatically register all placeable blocks as items (`block:<id>`)
for (const key of Object.keys(BLOCK_DEFS)) {
  const b = BLOCK_DEFS[key];
  if (b.id === BLOCK.AIR || b.id === BLOCK.WATER) continue;
  const itemKey = `block:${b.id}`;
  ITEMS[itemKey] = {
    id: itemKey,
    name: b.name,
    blockId: b.id,
    stackSize: 64,
    fuelValue:
      b.id === BLOCK.OAK_LOG ||
      b.id === BLOCK.BIRCH_LOG ||
      b.id === BLOCK.SPRUCE_LOG
        ? 2
        : b.id === BLOCK.OAK_PLANKS ||
          b.id === BLOCK.BIRCH_PLANKS ||
          b.id === BLOCK.SPRUCE_PLANKS
        ? 1
        : 0,
    category: 'block',
  };
}

export function getItemDef(itemId) {
  return ITEMS[itemId] || null;
}

