// Face indices: 0:+X, 1:-X, 2:+Y(top), 3:-Y(bottom), 4:+Z(front), 5:-Z(back)
function allFaces(t) {
  return [t, t, t, t, t, t];
}

function columnFaces(top, side, bottom = top) {
  return [side, side, top, bottom, side, side];
}

function directionalFaces(top, bottom, front, side) {
  return [side, side, top, bottom, front, side];
}

