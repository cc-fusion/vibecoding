export function getDef(id) {
  return REGISTRY[id] || REGISTRY[BLOCK.AIR];
}

export function isSolidBlock(id) {
  const def = REGISTRY[id];
  return Boolean(def && def.isBlock && def.solid);
}

export function isOpaqueBlock(id) {
  const def = REGISTRY[id];
  return Boolean(def && def.isBlock && def.opaque);
}

export function getLightEmission(id) {
  const def = REGISTRY[id];
  return def && def.light ? def.light : 0;
}

export function canHarvestBlock(blockId, heldItemId) {
  const block = getDef(blockId);
  if (!block || !block.minTier) return true;
  const held = heldItemId ? getDef(heldItemId) : null;
  if (!held || held.toolType !== block.preferredTool) return false;
  return (held.tier || 0) >= block.minTier;
}

export function getRequiredToolHint(blockId) {
  const block = getDef(blockId);
  if (!block || !block.minTier) return null;
  const tierNames = { 1: 'Wooden', 2: 'Stone', 3: 'Iron', 4: 'Diamond' };
  const tierName = tierNames[block.minTier] || 'Wooden';
  const toolLabel = block.preferredTool === TOOL_TYPE.PICKAXE ? 'Pickaxe' : 'Tool';
  return `Requires ${tierName} ${toolLabel}`;
}

export function getMiningDuration(blockId, heldItemId, inWater = false, onGround = true) {
  const block = getDef(blockId);
  if (!block || block.unbreakable) return Infinity;
  if (block.hardness <= 0.08) return 0.06;

  const held = heldItemId ? getDef(heldItemId) : null;
  let speed = 1.0;

  if (held && held.toolType && held.toolType === block.preferredTool) {
    speed = held.speed || 2.0;
  } else if (held && held.toolType === TOOL_TYPE.SWORD && block.cutoutCube) {
    speed = 2.2;
  }

  let duration = block.hardness / speed;
  if (block.minTier && !canHarvestBlock(blockId, heldItemId)) {
    duration *= 2.6;
  }
  if (inWater) duration *= 1.8;
  if (!onGround) duration *= 1.35;

  return Math.max(0.08, duration);
}

