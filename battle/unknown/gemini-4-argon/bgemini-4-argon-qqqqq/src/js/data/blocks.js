export const BLOCKS = {};
for (const def of rawBlocks) {
  BLOCKS[def.id] = {
    isBlock: true,
    solid: def.solid !== undefined ? def.solid : true,
    opaque: def.opaque !== undefined ? def.opaque : true,
    breakable: def.breakable !== undefined ? def.breakable : true,
    replaceable: def.replaceable || false,
    liquid: def.liquid || false,
    translucent: def.translucent || false,
    cutout: def.cutout || false,
    slippery: def.slippery || false,
    interactive: def.interactive || false,
    shape: def.shape || BLOCK_SHAPES.CUBE,
    hardness: def.hardness ?? 1.0,
    preferredTool: def.preferredTool || TOOL_TYPES.NONE,
    minTier: def.minTier || TOOL_TIERS.NONE,
    lightLevel: def.lightLevel || 0,
    fuelTime: def.fuelTime || 0,
    foodRestore: def.foodRestore || 0,
    contactDamage: def.contactDamage || 0,
    stackSize: 64,
    category: def.category || 'building',
    inCreativePalette: def.inCreativePalette !== undefined ? def.inCreativePalette : def.id !== BLOCK.AIR,
    sound: def.sound || SOUND_GROUPS.STONE,
    textures: def.textures || { all: 'stone' },
    tintTop: def.tintTop || null,
    tintAll: def.tintAll || null,
    drop: def.drop || (() => [{ id: def.id, count: 1 }]),
    ...def,
  };
}

export function getBlock(id) {
  return BLOCKS[id] || BLOCKS[BLOCK.AIR];
}
