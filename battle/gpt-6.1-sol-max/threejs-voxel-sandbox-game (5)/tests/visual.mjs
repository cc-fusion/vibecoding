import { chromium } from '@playwright/test';
import fs from 'node:fs';

fs.mkdirSync('artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 });
page.setDefaultTimeout(60000);
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
async function capture(name) {
  await page.waitForTimeout(600);
  await page.evaluate(() => window.__everwild.renderer.setAnimationLoop(null));
  await page.screenshot({ path: `artifacts/${name}.png`, timeout: 120000 });
  await page.evaluate(() => { window.__everwild.previousTime = 0; window.__everwild.renderer.setAnimationLoop(window.__everwild.frame); });
}
const started = Date.now();
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Enter your world', exact: true }).waitFor({ state: 'visible', timeout: 90000 });
await page.waitForFunction(() => window.__everwild.queue.length === 0, null, { timeout: 90000 });
await page.waitForTimeout(2000);
await capture('welcome');
console.log('READY_MS', Date.now() - started);
console.log('CANVAS', await page.locator('.world-canvas').evaluate(canvas => ({ width: canvas.width, height: canvas.height })));
console.log('SCENE', await page.evaluate(() => ({ position: window.__everwild.position.toArray(), triangles: window.__everwild.renderer.info.render.triangles, fps: window.__everwild.fps, pitch: window.__everwild.pitch })));
await page.getByRole('button', { name: 'Open backpack and crafting', exact: true }).click();
await page.getByRole('dialog').waitFor();
await capture('backpack');
await page.getByRole('button', { name: 'Craft workbench', exact: true }).click();
await page.waitForTimeout(350);
console.log('CRAFT', await page.locator('.game-toast').allTextContents());
console.log('SAVE', await page.evaluate(() => JSON.parse(localStorage.getItem('everwild.worlds.v1') || '[]').map(w => ({ name: w.name, inventory: w.inventory, crafted: w.stats.crafted }))));
await page.getByRole('button', { name: 'Close dialog' }).click();
await page.getByRole('button', { name: 'How to play', exact: true }).click();
await capture('guide');
await page.getByRole('button', { name: 'The local atlas', exact: true }).click();
await page.locator('.world-map').click({ position: { x: 80, y: 120 } });
await capture('atlas');
console.log('WAYPOINT', await page.locator('.text-button').allTextContents());
await page.getByRole('button', { name: 'Close dialog' }).click();
await page.getByRole('button', { name: 'Enter your world', exact: true }).click();
await page.waitForTimeout(600);
console.log('POINTER_LOCK', await page.evaluate(() => !!document.pointerLockElement));
await page.keyboard.down('KeyW');
await page.waitForTimeout(1600);
await page.keyboard.up('KeyW');
await capture('gameplay');
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
console.log('PAUSE', await page.locator('.modal-panel').getAttribute('class'));
console.log('ERRORS', errors);
await browser.close();